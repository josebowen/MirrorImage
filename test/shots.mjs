import puppeteer from 'puppeteer-core';
import { mkdirSync } from 'node:fs';
const [w, h, tag] = [+process.argv[2] || 1600, +process.argv[3] || 900, process.argv[4] || 'desk'];
mkdirSync('test/out', { recursive: true });
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage(); await p.setViewport({ width: w, height: h });
const errs = []; p.on('console', (m) => { if (m.type() === 'error' && !/fonts|ERR_/.test(m.text())) errs.push(m.text()); }); p.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message));
await p.goto('file://' + process.cwd() + '/index.html?dtcap=0.3');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (n) => { await wait(1500); await p.screenshot({ path: `test/out/${tag}-${n}.png` }); };
const D = (f, ...a) => p.evaluate(f, ...a);
await wait(2500); await shot('01-title');
const log = {};
log.base = await D(() => { const s = __demo.state(); return { A: s.configA, B: s.configB, atoms: s.atoms, search: __demo.search() }; });
await D(() => { __demo.go('mirror', 'predict'); }); await shot('02-mirror-predict');
await D(() => { __demo.predict('m', 'no'); __demo.act('mirrorTry'); __demo.rotate(0.9, 0.3); }); await shot('03-mirror-try');
await D(() => __demo.act('mirrorCheck')); await shot('04-mirror-done');
await D(() => { __demo.go('center'); }); await wait(800); await D(() => __demo.pickKind('ring')); await shot('05-center-wrong');
await D(() => __demo.pickKind('center')); await shot('06-center-right');
await D(() => { __demo.go('rank'); }); await wait(800); await D(() => __demo.pickKind('ring')); await wait(300); await D(() => __demo.pickKind('acid')); await wait(300); await D(() => __demo.pickKind('ring')); await wait(300); await D(() => __demo.pickKind('ch3', 'Me')); await shot('07-rank-done');
log.rank = await D(() => __demo.state());
await D(() => { __demo.go('turn'); __demo.act('showTurn'); }); await wait(6000); await shot('08-turn-call'); log.turn = await D(() => __demo.state());
await D(() => { document.querySelector('input[name=c][value=S]')?.click(); }); await shot('09-turn-done');
await D(() => { __demo.go('pocket'); }); await shot('10-pocket-predict');
await D(() => { __demo.predict('p', 'one'); __demo.act('dockA'); }); await wait(2500); await shot('11-dockA'); await D(() => __demo.act('showDock')); await wait(7000); await shot('12-seatedA'); log.seat = await D(() => __demo.state());
await D(() => { __demo.act('dockB'); }); await wait(3000); await D(() => __demo.rotate(0.5, 0.2)); await shot('13-dockB'); log.dockB = await D(() => __demo.state());
await D(() => { __demo.act('giveUp'); }); await shot('14-pocket-done');
await D(() => { __demo.act('next'); }); await wait(2000); await shot('15-debrief');
await D(() => __demo.act('about')); await shot('16-about');
console.log(JSON.stringify(log)); console.log('ERRORS', errs.length, errs.slice(0, 6));
await b.close();
